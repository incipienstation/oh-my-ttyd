#!/usr/bin/env node

import {readFile, writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import path from 'node:path';

const repositoryRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const manifestPath = path.join(repositoryRoot, 'protocol/clipboard-upload.json');
const manifest = JSON.parse(await readFile(manifestPath, 'utf8'));

function assert(condition, message) {
  if (!condition) throw new Error(`Invalid clipboard protocol manifest: ${message}`);
}

function validateManifest() {
  assert(manifest.defaults && typeof manifest.defaults === 'object', 'defaults must be an object');
  for (const name of ['maxUploadBytes', 'ttlSeconds', 'maxChunkBytes']) {
    const value = manifest.defaults[name];
    assert(Number.isSafeInteger(value) && value > 0, `defaults.${name} must be a positive integer`);
  }
  assert(
    manifest.defaults.maxChunkBytes <= 0x7fffffff,
    'defaults.maxChunkBytes must fit json_object_new_int'
  );

  assert(manifest.commands && typeof manifest.commands === 'object', 'commands must be an object');
  const commandNames = new Set();
  for (const requiredDirection of ['serverToClient', 'clientToServer']) {
    assert(
      manifest.commands[requiredDirection] && typeof manifest.commands[requiredDirection] === 'object',
      `commands.${requiredDirection} must be an object`
    );
  }
  for (const [direction, commands] of Object.entries(manifest.commands)) {
    const values = Object.values(commands);
    assert(new Set(values).size === values.length, `${direction} command values must be unique`);
    for (const [name, value] of Object.entries(commands)) {
      assert(/^[A-Z][A-Z0-9_]*$/.test(name), `${direction}.${name} is not a C identifier`);
      assert(!commandNames.has(name), `${name} is duplicated across command directions`);
      assert(typeof value === 'string' && /^[\x20-\x7e]$/.test(value), `${direction}.${name} must be one ASCII byte`);
      commandNames.add(name);
    }
  }

  assert(Array.isArray(manifest.imageTypes) && manifest.imageTypes.length > 0, 'imageTypes must be non-empty');
  const mimes = new Set();
  const extensions = new Set();
  for (const imageType of manifest.imageTypes) {
    assert(/^image\/[a-z0-9.+-]+$/.test(imageType.mime), `${imageType.mime} is not an image MIME type`);
    assert(/^[a-z0-9]+$/.test(imageType.extension), `${imageType.extension} is not a safe extension`);
    assert(!mimes.has(imageType.mime), `${imageType.mime} is duplicated`);
    assert(!extensions.has(imageType.extension), `${imageType.extension} is duplicated`);
    mimes.add(imageType.mime);
    extensions.add(imageType.extension);
    assert(imageType.signatureVariants.length > 0, `${imageType.mime} needs a signature`);
    for (const variant of imageType.signatureVariants) {
      assert(variant.length > 0, `${imageType.mime} has an empty signature variant`);
      for (const part of variant) {
        assert(Number.isSafeInteger(part.offset) && part.offset >= 0, `${imageType.mime} has an invalid offset`);
        assert(/^(?:[0-9a-fA-F]{2})+$/.test(part.hex), `${imageType.mime} has invalid signature hex`);
      }
    }
  }
}

function cBytes(hex) {
  return hex.match(/.{2}/g).map(value => `0x${value.toLowerCase()}`).join(', ');
}

function generateHeader() {
  const signatureSize = Math.max(
    ...manifest.imageTypes.flatMap(imageType =>
      imageType.signatureVariants.flatMap(variant =>
        variant.map(part => part.offset + part.hex.length / 2)
      )
    )
  );
  const mimeSize = Math.max(...manifest.imageTypes.map(imageType => imageType.mime.length + 1));
  const commandLines = Object.values(manifest.commands)
    .flatMap(commands => Object.entries(commands))
    .map(([name, value]) => `#define ${name} '${value}'`)
    .join('\n');

  return `/* Generated by scripts/generate-clipboard-protocol.mjs. Do not edit. */
#ifndef TTYD_CLIPBOARD_PROTOCOL_GENERATED_H
#define TTYD_CLIPBOARD_PROTOCOL_GENERATED_H

#include <stddef.h>
#include <stdint.h>

#define CLIPBOARD_UPLOAD_DEFAULT_MAX_SIZE ${manifest.defaults.maxUploadBytes}U
#define CLIPBOARD_UPLOAD_DEFAULT_TTL ${manifest.defaults.ttlSeconds}
#define CLIPBOARD_UPLOAD_MAX_CHUNK_SIZE ${manifest.defaults.maxChunkBytes}U
#define CLIPBOARD_UPLOAD_SIGNATURE_SIZE ${signatureSize}U
#define CLIPBOARD_UPLOAD_MIME_MAX ${mimeSize}U

${commandLines}

typedef struct {
  size_t offset;
  const uint8_t *bytes;
  size_t length;
} clipboard_magic_part_t;

typedef struct {
  const clipboard_magic_part_t *parts;
  size_t part_count;
} clipboard_signature_variant_t;

typedef struct {
  const char *mime;
  const char *extension;
  const clipboard_signature_variant_t *variants;
  size_t variant_count;
} clipboard_image_type_t;

extern const clipboard_image_type_t clipboard_image_types[];
extern const size_t clipboard_image_type_count;

#endif
`;
}

function generateSource() {
  const declarations = [];
  const imageEntries = [];

  manifest.imageTypes.forEach((imageType, typeIndex) => {
    const variantEntries = [];
    imageType.signatureVariants.forEach((variant, variantIndex) => {
      const partEntries = [];
      variant.forEach((part, partIndex) => {
        const prefix = `clipboard_magic_${typeIndex}_${variantIndex}_${partIndex}`;
        declarations.push(`static const uint8_t ${prefix}_bytes[] = {${cBytes(part.hex)}};`);
        partEntries.push(`  {${part.offset}U, ${prefix}_bytes, sizeof(${prefix}_bytes)}`);
      });
      const partsName = `clipboard_magic_${typeIndex}_${variantIndex}_parts`;
      declarations.push(
        `static const clipboard_magic_part_t ${partsName}[] = {\n${partEntries.join(',\n')}\n};`
      );
      variantEntries.push(`  {${partsName}, sizeof(${partsName}) / sizeof(${partsName}[0])}`);
    });
    const variantsName = `clipboard_magic_${typeIndex}_variants`;
    declarations.push(
      `static const clipboard_signature_variant_t ${variantsName}[] = {\n${variantEntries.join(',\n')}\n};`
    );
    imageEntries.push(
      `  {"${imageType.mime}", "${imageType.extension}", ${variantsName}, sizeof(${variantsName}) / sizeof(${variantsName}[0])}`
    );
  });

  return `/* Generated by scripts/generate-clipboard-protocol.mjs. Do not edit. */
#include "clipboard_protocol.generated.h"

${declarations.join('\n\n')}

const clipboard_image_type_t clipboard_image_types[] = {
${imageEntries.join(',\n')}
};

const size_t clipboard_image_type_count = sizeof(clipboard_image_types) / sizeof(clipboard_image_types[0]);
`;
}

function generateTypeScript() {
  const commands = Object.values(manifest.commands)
    .flatMap(commandGroup => Object.entries(commandGroup))
    .map(([name, value]) => `        ${name}: '${value}',`)
    .join('\n');
  const mimes = manifest.imageTypes.map(imageType => `'${imageType.mime}'`).join(', ');

  return `// Generated by scripts/generate-clipboard-protocol.mjs. Do not edit.
export const ClipboardProtocol = {
    defaults: {
        maxUploadBytes: ${manifest.defaults.maxUploadBytes},
        ttlSeconds: ${manifest.defaults.ttlSeconds},
        maxChunkBytes: ${manifest.defaults.maxChunkBytes},
    },
    commands: {
${commands}
    },
    supportedImageTypes: [${mimes}],
} as const;
`;
}

async function updateGeneratedFile(relativePath, contents, check) {
  const outputPath = path.join(repositoryRoot, relativePath);
  const current = await readFile(outputPath, 'utf8').catch(() => undefined);
  if (current === contents) return true;
  if (check) {
    console.error(`${relativePath} is out of date; run node scripts/generate-clipboard-protocol.mjs`);
    return false;
  }
  await writeFile(outputPath, contents);
  console.log(`generated ${relativePath}`);
  return true;
}

validateManifest();
const check = process.argv.includes('--check');
const results = await Promise.all([
  updateGeneratedFile('src/clipboard_protocol.generated.h', generateHeader(), check),
  updateGeneratedFile('src/clipboard_protocol.generated.c', generateSource(), check),
  updateGeneratedFile(
    'html/src/components/terminal/xterm/clipboard-protocol.generated.ts',
    generateTypeScript(),
    check
  ),
]);
if (results.some(result => !result)) process.exitCode = 1;
